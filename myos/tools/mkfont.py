# Converts a PSF console font into font.h (8x16 glyphs for ASCII 0-127).
import gzip, sys
data = gzip.open(sys.argv[1]).read()
if data[:2] == b'\x36\x04':            # PSF1
    mode, h = data[2], data[3]; n = 512 if mode & 1 else 256
    glyphs = data[4:4+n*h]; w = 8; tab = data[4+n*h:] if mode & 2 else None; psf1 = True
else:                                   # PSF2
    import struct
    _, _, hs, flags, n, gsz, h, w = struct.unpack('<8I', data[:32])
    glyphs = data[hs:hs+n*gsz]; tab = data[hs+n*gsz:] if flags & 1 else None; psf1 = False
umap = {}
if tab:
    i = 0; g = 0
    if psf1:
        while g < n and i + 1 < len(tab):
            u = tab[i] | tab[i+1] << 8; i += 2
            if u == 0xFFFF: g += 1
            elif u != 0xFFFE: umap.setdefault(u, g)
    else:
        for g, entry in enumerate(tab.split(b'\xff')[:n]):
            for ch in entry.split(b'\xfe')[0].decode('utf-8', 'ignore'):
                umap.setdefault(ord(ch), g)
out = ["/* Generated by tools/mkfont.py - 8x16 bitmap font, ASCII 0-127 */",
       "static const unsigned char font8x16[128][16] = {"]
for c in range(128):
    g = umap.get(c, c if c < n else 0) if c >= 32 else 0
    rows = glyphs[g*h:(g+1)*h][:16]
    out.append("  {" + ",".join("0x%02x" % b for b in rows) + "},")
out.append("};")
open(sys.argv[2], 'w').write("\n".join(out) + "\n")
